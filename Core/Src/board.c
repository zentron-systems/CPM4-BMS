bool board_can2_tx_cell_voltage_frame(const int32_t cell_mv[],
                                      uint8_t       cell_count,
                                      uint8_t       frame_index)
{
    uint8_t addr = board_get_address();
    uint8_t tx_data[8];
    uint8_t slot;

    if (frame_index >= CAN2_CELL_FRAMES)
    {
        return false;
    }

    memset(tx_data, 0, sizeof(tx_data));

    for (slot = 0; slot < CAN2_CELLS_PER_FRAME; slot++)
    {
        uint8_t  cell_index = (uint8_t)(frame_index * CAN2_CELLS_PER_FRAME
                                        + slot);
        uint16_t mv = 0U;

        if (cell_mv != NULL && cell_index < cell_count)
        {
            int32_t raw_mv = cell_mv[cell_index];
            if (raw_mv > 0)
            {
                mv = (uint16_t)raw_mv;
            }
        }

        tx_data[slot * 2U]     = (uint8_t)(mv >> 8);
        tx_data[slot * 2U + 1] = (uint8_t)(mv & 0xFF);
    }

    return board_can_tx_standard_frame(&hfdcan2,
                                       CAN2_ID_CELLS_BASE
                                       + ((uint32_t)frame_index
                                          * CAN2_CELL_FRAME_STEP)
                                       + (uint32_t)addr,
                                       tx_data);
}

bool board_can2_tx_cell_voltages(const int32_t cell_mv[],
                                 uint8_t       cell_count)
{
    uint8_t  frame;
    bool     all_ok = true;

    for (frame = 0; frame < CAN2_CELL_FRAMES; frame++)
    {
        if (!board_can2_tx_cell_voltage_frame(cell_mv,
                                              cell_count,
                                              frame))
        {
            all_ok = false;
            break;
        }
    }

    return all_ok;
}

