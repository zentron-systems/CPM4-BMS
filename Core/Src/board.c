static bool board_can_tx_standard_frame(FDCAN_HandleTypeDef *hfdcan,
                                        uint32_t             std_id,
                                        uint8_t              tx_data[8])
{
    FDCAN_TxHeaderTypeDef tx_header;

    tx_header.Identifier          = std_id;
    tx_header.IdType              = FDCAN_STANDARD_ID;
    tx_header.TxFrameType         = FDCAN_DATA_FRAME;
    tx_header.DataLength          = FDCAN_DLC_BYTES_8;
    tx_header.ErrorStateIndicator = FDCAN_ESI_ACTIVE;
    tx_header.BitRateSwitch       = FDCAN_BRS_OFF;
    tx_header.FDFormat            = FDCAN_CLASSIC_CAN;
    tx_header.TxEventFifoControl  = FDCAN_NO_TX_EVENTS;
    tx_header.MessageMarker       = 0;

    if (HAL_FDCAN_AddMessageToTxFifoQ(hfdcan,
                                      &tx_header,
                                      tx_data) != HAL_OK)
    {
        return false;
    }

    return true;
}

static bool board_can_tx_heartbeat_bus(FDCAN_HandleTypeDef *hfdcan,
                                       uint8_t             *rolling_counter,
                                       int32_t              min_cell_mv,
                                       int32_t              max_cell_mv,
                                       uint8_t              cell_count,
                                       uint8_t              state)
{
    uint8_t               tx_data[8];
    uint8_t               addr = board_get_address();

    tx_data[0] = addr;
    tx_data[1] = state;
    tx_data[2] = cell_count;

    {
        uint16_t min_mv = (min_cell_mv > 0)
                          ? (uint16_t)min_cell_mv : 0U;
        tx_data[3] = (uint8_t)(min_mv >> 8);
        tx_data[4] = (uint8_t)(min_mv & 0xFF);
    }

    {
        uint16_t max_mv = (max_cell_mv > 0)
                          ? (uint16_t)max_cell_mv : 0U;
        tx_data[5] = (uint8_t)(max_mv >> 8);
        tx_data[6] = (uint8_t)(max_mv & 0xFF);
    }

    tx_data[7] = *rolling_counter;
    (*rolling_counter)++;

    return board_can_tx_standard_frame(hfdcan,
                                       CAN_ID_HEARTBEAT_BASE
                                       + (uint32_t)addr,
                                       tx_data);
}

static bool board_can_rx_message_bus(FDCAN_HandleTypeDef *hfdcan,
                                     uint32_t            *std_id,
                                     uint8_t              rx_data[8])
{
    FDCAN_RxHeaderTypeDef rx_header;

    if (HAL_FDCAN_GetRxFifoFillLevel(hfdcan, FDCAN_RX_FIFO0) == 0)
    {
        return false;
    }

    if (HAL_FDCAN_GetRxMessage(hfdcan,
                               FDCAN_RX_FIFO0,
                               &rx_header,
                               rx_data) != HAL_OK)
    {
        return false;
    }

    if (rx_header.IdType != FDCAN_STANDARD_ID ||
        rx_header.RxFrameType != FDCAN_DATA_FRAME ||
        rx_header.DataLength != FDCAN_DLC_BYTES_8)
    {
        return false;
    }

    if (std_id != NULL)
    {
        *std_id = rx_header.Identifier;
    }

    return true;
}

static int8_t board_can_rx_heartbeat_bus(FDCAN_HandleTypeDef *hfdcan,
                                         uint8_t              rx_data[8])
{
    uint32_t sender_id;

    if (!board_can_rx_message_bus(hfdcan, &sender_id, rx_data))
    {
        return -1;
    }

    if ((sender_id < CAN_ID_HEARTBEAT_BASE) ||
        (sender_id > (CAN_ID_HEARTBEAT_BASE + 7U)))
    {
        return -1;
    }

    sender_id -= CAN_ID_HEARTBEAT_BASE;
    return (int8_t)sender_id;
}


