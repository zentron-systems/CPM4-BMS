/* USB CDC Virtual COM Port — mirrors all terminal output.
 * CDC_Transmit_FS() is generated by CubeMX USB Device middleware.
 * If USB is not connected, the call returns USBD_BUSY instantly
 * with zero delay — no stall, no performance impact. */
#include "usbd_cdc_if.h"


/* ===============================================================
 *  USART1 DMA + USB CDC transmit helpers
 *
 *  One shared static buffer is the DMA source for ALL terminal
 *  output.  Every transmit goes to BOTH USART1 (via DMA) and
 *  USB CDC (via packet memory copy), so PuTTY on the UART and
 *  a USB terminal see identical output.
 *
 *  USB CDC is ~70x faster than 115200 baud UART, so the mirror
 *  adds negligible overhead.  CDC_Transmit_FS() copies data into
 *  the USB peripheral's packet memory during the call — by the
 *  time it returns, the source buffer is free for UART DMA.
 *
 *  Two usage patterns:
 *
 *  Pattern A — small strings (dbg calls):
 *    uart1_dma_send(data, len);
 *    // copies into static buffer, sends to CDC, fires DMA
 *
 *  Pattern B — large screen buffer (display engine):
 *    char *buf = (char *)uart1_dma_buf();  // get buffer pointer
 *    int pos = snprintf(buf, UART1_TX_SIZE, ...);  // build in-place
 *    uart1_dma_send_buf((uint16_t)pos);    // send to CDC + DMA
 *
 *  Both patterns wait for any in-progress DMA to finish before
 *  touching the buffer, ensuring no data corruption.
 * =============================================================== */
static uint8_t uart1_tx_buf[UART1_TX_SIZE];


/* ---- uart1_dma_wait ----
 * Spin until the UART TX state returns to READY, meaning the
 * previous DMA transfer has fully completed.
 *
 * HAL sets gState = HAL_UART_STATE_BUSY_TX when DMA starts,
 * and the DMA-complete ISR resets it to HAL_UART_STATE_READY.
 *
 * We check for != READY rather than == BUSY_TX because gState
 * can also be HAL_UART_STATE_BUSY_TX_RX if both directions
 * are active simultaneously (unlikely for USART1, but safe). */
void uart1_dma_wait(void)
{
    while (huart1.gState != HAL_UART_STATE_READY)
    {
        /* Spin — typically < 1 ms for small debug strings,
         * up to ~130 ms worst case for a full 1536-byte buffer
         * at 115200 bps.  No HAL_Delay needed because this is
         * genuinely just waiting for hardware to finish. */
    }
}


/* ---- uart1_dma_send ----
 * Copy data into the static DMA buffer, mirror to USB CDC,
 * then fire a UART DMA transfer.
 *
 * USB CDC goes first because CDC_Transmit_FS() copies the data
 * into the USB peripheral's packet memory during the call.
 * Once it returns, our buffer is free for UART DMA to read.
 *
 * If USB is not connected, CDC_Transmit_FS() returns USBD_BUSY
 * instantly — no stall.  We ignore the return value because
 * debug output is best-effort on USB. */
void uart1_dma_send(const uint8_t *data, uint16_t len)
{
    if (len == 0) { return; }

    uart1_dma_wait();     /* Wait for previous transfer */

    /* Clamp to buffer size (safety) */
    if (len > UART1_TX_SIZE)
    {
        len = UART1_TX_SIZE;
    }

    memcpy(uart1_tx_buf, data, len);

    /* Mirror to USB CDC (non-blocking, fail-safe) */
    CDC_Mirror_Write_FS(uart1_tx_buf, len);

    /* Fire UART DMA */
    (void)HAL_UART_Transmit_DMA(&huart1, uart1_tx_buf, len);
}


/* ---- uart1_dma_buf ----
 * Returns a pointer to the internal DMA buffer so callers can
 * build content directly with snprintf, avoiding a memcpy.
 *
 * Waits for any in-progress DMA to finish first — the buffer
 * must not be written while DMA is still reading from it. */
uint8_t *uart1_dma_buf(void)
{
    uart1_dma_wait();
    return uart1_tx_buf;
}


/* ---- uart1_dma_send_buf ----
 * Mirror the internal buffer to USB CDC, then fire a UART DMA
 * transfer.  Call after building content via uart1_dma_buf().
 *
 * Does NOT wait — returns immediately while DMA runs in the
 * background.  The CPU is free to do other work (run the
 * balance state machine, check NFAULT, etc). */
void uart1_dma_send_buf(uint16_t len)
{
    if (len == 0) { return; }

    if (len > UART1_TX_SIZE)
    {
        len = UART1_TX_SIZE;
    }

    /* Mirror to USB CDC (non-blocking, fail-safe) */
    CDC_Mirror_Write_FS(uart1_tx_buf, len);

    /* Fire UART DMA */
    (void)HAL_UART_Transmit_DMA(&huart1, uart1_tx_buf, len);
}


/* ---------------------------------------------------------------
 *  Small helper — prints a string to the debug UART via DMA.
 *  Only sends when sys_debug is true (debug mode).
 *
 *  Uses uart1_dma_send() which copies the string into the
 *  static DMA buffer before firing, so it's safe to call with
 *  stack-local format buffers (like those in dbg_hex/dbg_frame).
 * --------------------------------------------------------------- */
static void board_dbg(const char *msg)
{
    if (sys_debug)
    {
        uart1_dma_send((const uint8_t *)msg,
                       (uint16_t)strlen(msg));
    }
}


/* ===============================================================
 *  Board identity and configuration state
 *
 *  These are set by board_setup_from_config_jumpers() (when
 *  CONFIG_NO_APP is HIGH) or by board_set_defaults() (when
 *  CONFIG_NO_APP is LOW).  The getters below let application.c
 *  and other modules read these values without knowing which
 *  path set them.
 * =============================================================== */
static uint8_t  g_board_address       = 0;     /* 0=master, 1-7=slave */
static uint8_t  g_num_expected_slaves = 0;     /* 0..7                */
static uint8_t  g_active_cell_count   = 16;    /* 6..16               */
static uint16_t g_bal_floor_mv        = 3800;  /* Balance floor (mV)  */

/* The PCB config jumpers pull the MCU input up to 3.3 V when fitted.
 * Open jumpers therefore read back LOW via the MCU's internal pull-down,
 * while fitted jumpers read HIGH and represent a logical '1'. */
static uint8_t board_jumper_bit(dpin_t pin)
{
    return (digital_read(pin) == HIGH) ? 1U : 0U;
}

/* Read the board identity jumpers that define CAN address and the
 * expected slave count on the master.  These are physical topology
 * settings, so we keep using them even when the rest of the board
 * configuration comes from the app/defaults path. */
void board_refresh_identity_from_jumpers(void)
{
    uint8_t addr_j1 = board_jumper_bit(PB9);
    uint8_t addr_j2 = board_jumper_bit(PC12);
    uint8_t addr_j3 = board_jumper_bit(PC2);

    uint8_t slv_j2 = board_jumper_bit(PC3);
    uint8_t slv_j1 = board_jumper_bit(PA0);
    uint8_t slv_j0 = board_jumper_bit(PA1);

    g_board_address = (uint8_t)((addr_j1 << 2) | (addr_j2 << 1) | addr_j3);
    g_num_expected_slaves = (uint8_t)((slv_j2 << 2) | (slv_j1 << 1) | slv_j0);
}


uint8_t board_get_address(void)
{
    return g_board_address;
}

uint8_t board_get_num_expected_slaves(void)
{
    return g_num_expected_slaves;
}

uint8_t board_get_active_cell_count(void)
{
    return g_active_cell_count;
}

uint16_t board_get_bal_floor_mv(void)
{
    return g_bal_floor_mv;
}

void board_load_runtime_config_from_jumpers(void)
{
    uint8_t j1;
    uint8_t j2;
    uint8_t j3;
    uint8_t j4;
    uint8_t jumper_value;
    uint8_t cell_count;
    uint8_t is_lithium_ion;
    uint8_t is_hicap;

    board_refresh_identity_from_jumpers();

    j1 = board_jumper_bit(PB3);
    j2 = board_jumper_bit(PB4);
    j3 = board_jumper_bit(PB5);
    j4 = board_jumper_bit(PB6);
    jumper_value = (uint8_t)((j1 << 3) | (j2 << 2) | (j3 << 1) | j4);
    cell_count = jumper_value + 6U;

    if (cell_count > 16U)
    {
        cell_count = 16U;
    }

    g_active_cell_count = cell_count;
    is_lithium_ion = board_jumper_bit(PB8);
    is_hicap       = board_jumper_bit(PB7);

    if (is_lithium_ion)
    {
        g_bal_floor_mv = is_hicap ? 3400U : 3500U;
    }
    else
    {
        g_bal_floor_mv = 2800U;
    }
}

void board_load_runtime_defaults(void)
{
    board_refresh_identity_from_jumpers();
    g_active_cell_count = 16U;
    g_bal_floor_mv      = 3800U;
}


/* ===============================================================
 *  board_setup_from_config_jumpers
 *
 *  Reads ALL hardware config jumpers on the PCB and configures
 *  the BQ79616 and MCU warning thresholds accordingly.
 *
 *  Called when CONFIG_NO_APP (PC10) is fitted at startup — this
 *  means the board is being deployed standalone without a PC
 *  or app to configure it.
 *
 *  JUMPER PIN MAP  (from CPM-4-16.ioc):
 *
 *    Board address (3 bits):
 *      CONFIG_ADDRESS_J1 = PB9   (MSB, bit 2)
 *      CONFIG_ADDRESS_J2 = PC12  (bit 1)
 *      CONFIG_ADDRESS_J3 = PC2   (LSB, bit 0)
 *      000=master, 001=slave1 ... 111=slave7
 *
 *    Expected slave count (3 bits):
 *      NUM_SLAVES_J2 = PC3  (MSB, bit 2)
 *      NUM_SLAVES_J1 = PA0  (bit 1)
 *      NUM_SLAVES_J0 = PA1  (LSB, bit 0)
 *      Binary 0..7
 *
 *    Cell count (4 bits):
 *      CONFIG_CELLS_J1 = PB3  (MSB, bit 3)
 *      CONFIG_CELLS_J2 = PB4  (bit 2)
 *      CONFIG_CELLS_J3 = PB5  (bit 1)
 *      CONFIG_CELLS_J4 = PB6  (LSB, bit 0)
 *      Binary value + 6 = number of cells (6..16)
 *
 *    Chemistry and mode:
 *      CONFIG_ION_LFP       = PB8  (1=Li-Ion, 0=LiFePO4)
 *      CONFIG_HICAP_LONGLIFE = PB7 (1=Hi-Cap, 0=Long-Life)
 *
 *  All config pins use internal pull-downs in MX_GPIO_Init().
 *  Open jumper   -> GPIO LOW  -> logical 0
 *  Fitted jumper -> GPIO HIGH -> logical 1
 * =============================================================== */
bool board_setup_from_config_jumpers(uint8_t dev_id)
{
    board_refresh_identity_from_jumpers();

    /* ------ Step 1: Read board address jumpers ------
     *
     * Three bits: J1(MSB) J2 J3(LSB) -> 0..7
     *   0 = master board
     *   1..7 = slave boards on the daisy chain
     */
    uint8_t addr_j1 = (g_board_address >> 2) & 0x1U;
    uint8_t addr_j2 = (g_board_address >> 1) & 0x1U;
    uint8_t addr_j3 = g_board_address & 0x1U;

    /* ------ Step 2: Read expected slave count jumpers ------
     *
     * Three bits: J2(MSB) J1 J0(LSB) -> 0..7
     * Only meaningful on the master board, but we read it
     * regardless so the display can show the setting.
     */
    /* ------ Step 3: Read the four cell-count jumpers ------
     *
     * The jumpers form a 4-bit binary number:
     *   J1 = bit 3 (MSB), J2 = bit 2, J3 = bit 1, J4 = bit 0 (LSB)
     *
     * That binary value (0..10) is added to 6 to give the cell count.
     * For example:  J1=1 J2=0 J3=1 J4=0  ->  binary 1010 = 10  ->  10+6 = 16 cells.
     *
     * Values above 10 (i.e. 11..15) are invalid because the BQ79616
     * only supports up to 16 cells, and 6+10 = 16.
     */
    uint8_t j1 = board_jumper_bit(PB3);  /* CONFIG_CELLS_J1 */
    uint8_t j2 = board_jumper_bit(PB4);  /* CONFIG_CELLS_J2 */
    uint8_t j3 = board_jumper_bit(PB5);  /* CONFIG_CELLS_J3 */
    uint8_t j4 = board_jumper_bit(PB6);  /* CONFIG_CELLS_J4 */

    /* Combine the four bits into one number (0..15) */
    uint8_t jumper_value = (uint8_t)((j1 << 3) | (j2 << 2) | (j3 << 1) | j4);

    /* Cell count = jumper value + 6.  Valid jumper range is 0..10 -> 6..16 cells */
    uint8_t cell_count = jumper_value + 6;

    /* ------ Step 4: Read the chemistry jumper ------
     *
     * CONFIG_ION_LFP on PB8:
     *   HIGH (1) = Lithium-Ion  (NMC / NCA - higher voltage per cell)
     *   LOW  (0) = LiFePO4     (LFP - lower voltage per cell)
     */
    uint8_t is_lithium_ion = board_jumper_bit(PB8);

    /* ------ Step 5: Read the capacity / longevity jumper ------
     *
     * CONFIG_HICAP_LONGLIFE on PB7:
     *   HIGH (1) = High-Capacity mode   (charge fuller, discharge deeper)
     *   LOW  (0) = Long-Life mode       (gentler limits extend cycle life)
     */
    uint8_t is_hicap = board_jumper_bit(PB7);

    /* ------ Print what we read (debug) ------ */
    {
        char buf[160];

        snprintf(buf, sizeof(buf),
                 "\r\n=== BOARD CONFIG JUMPERS ===\r\n"
                 "  Raw addr   : J1=%u J2=%u J3=%u\r\n"
                 "  Address   : %u (%s)\r\n"
                 "  Exp slaves: %u\r\n",
                 addr_j1, addr_j2, addr_j3,
                 g_board_address,
                 (g_board_address == 0) ? "MASTER" : "SLAVE",
                 g_num_expected_slaves);
        board_dbg(buf);

        snprintf(buf, sizeof(buf),
                 "  Cells J1=%u J2=%u J3=%u J4=%u  -> %u cells\r\n"
                 "  Chemistry : %s\r\n"
                 "  Mode      : %s\r\n",
                 j1, j2, j3, j4, cell_count,
                 is_lithium_ion ? "Lithium-Ion" : "LiFePO4",
                 is_hicap       ? "High-Capacity" : "Long-Life");
        board_dbg(buf);
    }

    /* ------ Step 6: Validate the cell count ------
     *
     * The BQ79616 supports 6 to 16 cells.  If the jumper value
     * is above 10 the cell count exceeds 16 which is impossible.
     * Rather than sending a bad value to the chip, we stop here.
     */
    if (cell_count > 16)
    {
        char buf[80];

        snprintf(buf, sizeof(buf),
                 "  ERROR: jumper value %u -> %u cells (max 16)!\r\n",
                 jumper_value, cell_count);
        board_dbg(buf);
        board_dbg("=== BOARD CONFIG FAILED ===\r\n");
        return false;
    }

    g_active_cell_count = cell_count;

    /* ------ Step 7: Tell the BQ79616 how many cells are connected ------
     *
     * This writes the ACTIVE_CELL register so the ADC knows which
     * cell channels to scan.  Same as doing:
     *   bq79616_set_active_cells(0x01, 16);
     * ...but now the number comes from the jumpers instead of being hardcoded.
     */
    if (!bq79616_set_active_cells(dev_id, cell_count))
    {
        board_dbg("  ERROR: bq79616_set_active_cells failed!\r\n");
        board_dbg("=== BOARD CONFIG FAILED ===\r\n");
        return false;
    }

    /* ------ Step 8: Look up the OV and UV thresholds ------
     *
     * The correct thresholds depend on BOTH the chemistry type
     * and the capacity/longevity mode.  This gives four combos:
     *
     *   Chemistry    Mode         OV (mV)   UV (mV)   Bal Floor (mV)
     *   ------------ ------------ --------- --------- ---------------
     *   Lithium-Ion  High-Cap     4225      2850      3400
     *   Lithium-Ion  Long-Life    4175      3050*     3500
     *   LiFePO4      High-Cap     3650      2500      2800
     *   LiFePO4      Long-Life    3500      2950      2800
     *
     *  * NOTE: The original spec says Li-Ion Long-Life UV = 3450 mV,
     *    but the BQ79616 UV comparator maxes out at 3100 mV (see
     *    bq79616_set_uv_thresh).  We clamp to 3050 mV here which
     *    is the closest valid 50 mV step.  If you need 3450 mV
     *    protection you will need to do it in software by reading
     *    cell voltages periodically and checking yourself.
     *
     *  MCU warning thresholds are derived from the BQ thresholds:
     *    OV  warning = OV  - 25 mV  (early warning before BQ trips)
     *    BAL warning = OV  - 90 mV  (start balancing before OV)
     *    UV  warning = UV  + 50 mV  (early warning before BQ trips)
     */
    uint16_t ov_mv;         /* Overvoltage threshold in millivolts  */
    uint16_t uv_mv;         /* Undervoltage threshold in millivolts */

    if (is_lithium_ion)
    {
        if (is_hicap)
        {
            /* Li-Ion, High-Capacity: charge high, discharge deep */
            ov_mv        = 4225;
            uv_mv        = 2850;
            g_bal_floor_mv = 3400;
        }
        else
        {
            /* Li-Ion, Long-Life: gentler limits for more cycles  */
            ov_mv        = 4175;
            uv_mv        = 3050;   /* Clamped from 3450 - see note above */
            g_bal_floor_mv = 3500;
        }
    }
    else
    {
        if (is_hicap)
        {
            /* LiFePO4, High-Capacity */
            ov_mv        = 3650;
            uv_mv        = 2500;
            g_bal_floor_mv = 2800;
        }
        else
        {
            /* LiFePO4, Long-Life */
            ov_mv        = 3500;
            uv_mv        = 2950;
            g_bal_floor_mv = 2800;
        }
    }

    /* Print the thresholds we are about to apply */
    {
        char buf[128];

        snprintf(buf, sizeof(buf),
                 "  OV = %u mV, UV = %u mV, Bal floor = %u mV\r\n"
                 "  OV warn = %u, BAL warn = %u, UV warn = %u\r\n",
                 ov_mv, uv_mv, g_bal_floor_mv,
                 ov_mv - 25, ov_mv - 90, uv_mv + 50);
        board_dbg(buf);
    }

    /* ------ Step 9: Set the overvoltage threshold ------ */
    if (!bq79616_set_ov_thresh(dev_id, ov_mv))
    {
        board_dbg("  ERROR: bq79616_set_ov_thresh failed!\r\n");
        board_dbg("=== BOARD CONFIG FAILED ===\r\n");
        return false;
    }

    /* ------ Step 10: Set the undervoltage threshold ------ */
    if (!bq79616_set_uv_thresh(dev_id, uv_mv))
    {
        board_dbg("  ERROR: bq79616_set_uv_thresh failed!\r\n");
        board_dbg("=== BOARD CONFIG FAILED ===\r\n");
        return false;
    }

    /* ------ Step 11: Set MCU warning thresholds ------
     *
     * These are software thresholds checked every 500 ms in the
     * display refresh using live cell voltage reads.  They drive
     * MCU GPIO warning indicators:
     *   PA5 HIGH if any cell >= (OV - 25 mV)  overvoltage warning
     *   PA4 HIGH if any cell >= (OV - 90 mV)  balance warning
     *   PA6 HIGH if any cell <= (UV + 50 mV)  undervoltage warning
     */
    board_set_ov_warn_thresh(ov_mv - 25);
    board_set_bal_warn_thresh(ov_mv - 90);
    board_set_uv_warn_thresh(uv_mv + 50);

    /* ------ Done! ------ */
    board_dbg("=== BOARD CONFIG OK ===\r\n");
    return true;
}


/* ===============================================================
 *  board_set_defaults
 *
 *  Hardcoded safe configuration for when CONFIG_NO_APP is LOW
 *  (a PC or app will manage the board later via CAN/USB).
 *
 *  Sets Li-Ion Long-Life defaults:
 *    16 cells, OV=4175, UV=3100
 *    MCU warnings: OV=4150, BAL=4085, UV=3150
 *    Balance floor = 3800 mV
 *
 *  Board identity for CAN is still taken from the physical
 *  address/slave-count jumpers so multi-board setups work even
 *  in the app-managed/defaults path.
 * =============================================================== */
bool board_set_defaults(uint8_t dev_id)
{
    char identity_buf[96];
    uint8_t addr_j1;
    uint8_t addr_j2;
    uint8_t addr_j3;

    board_dbg("\r\n=== BOARD DEFAULTS (NO_APP=LOW) ===\r\n");

    board_refresh_identity_from_jumpers();
    g_active_cell_count   = 16;
    g_bal_floor_mv        = 3800;
    addr_j1 = (g_board_address >> 2) & 0x1U;
    addr_j2 = (g_board_address >> 1) & 0x1U;
    addr_j3 = g_board_address & 0x1U;

    snprintf(identity_buf, sizeof(identity_buf),
             "  Identity from jumpers: raw J1=%u J2=%u J3=%u, addr=%u (%s), slaves=%u\r\n",
             addr_j1, addr_j2, addr_j3,
             g_board_address,
             (g_board_address == BOARD_ADDR_MASTER) ? "MASTER" : "SLAVE",
             g_num_expected_slaves);
    board_dbg(identity_buf);

    if (!bq79616_set_active_cells(dev_id, 16))
    {
        board_dbg("  ERROR: set_active_cells failed!\r\n");
        return false;
    }

    if (!bq79616_set_ov_thresh(dev_id, 4175))
    {
        board_dbg("  ERROR: set_ov_thresh failed!\r\n");
        return false;
    }

    if (!bq79616_set_uv_thresh(dev_id, 3100))
    {
        board_dbg("  ERROR: set_uv_thresh failed!\r\n");
        return false;
    }

    board_set_ov_warn_thresh(4150);
    board_set_bal_warn_thresh(4085);
    board_set_uv_warn_thresh(3150);

    board_dbg("  16S, OV=4175, UV=3100\r\n");
    board_dbg("=== BOARD DEFAULTS OK ===\r\n");
    return true;
}


/* ===============================================================
 *  CONTACTOR CONTROL
 *
 *  Three TPS1H200A-Q1 smart high-side switches drive the battery
 *  contactors.  Each one is basically a fancy MOSFET with built-in
 *  protection and diagnostics:
 *
 *    IN pin       = MCU tells it to turn ON (HIGH) or OFF (LOW)
 *    FAULT pin    = open-drain output, pulled HIGH externally.
 *                   Goes LOW when there's a problem (overload,
 *                   short-to-ground, open load, or thermal issue).
 *    DIAG_EN pin  = enables/disables the diagnostic features.
 *                   All 3 drivers share one DIAG_EN line (PA15).
 *
 *  PIN MAP (from CPM-4-16.ioc):
 *
 *    Function            Pin    Direction   Notes
 *    ------------------  -----  ---------   ----------------------------
 *    DIAG_EN_CONTACTORS  PA15   output      Shared diag enable for all 3
 *    MCU_CONTACTOR-      PC9    output      Negative contactor IN
 *    MCU_CONTACTOR+      PD5    output      Positive contactor IN
 *    MCU_PRECHARGE       PD3    output      Precharge contactor IN
 *    MCU_CONTACTOR-FAULT PD2    input       Negative FAULT (active LOW)
 *    MCU_CONTACTOR+FAULT PC8    input       Positive FAULT (active LOW)
 *    MCU_PRECHARGE_FAULT PD4    input       Precharge FAULT (active LOW)
 *    MCU_HV_PRESENT      PB14   input       HIGH = HV bus is charged
 *
 * =============================================================== */


/* ---------------------------------------------------------------
 *  contactor_check_fault  -  Read a TPS1H200A FAULT pin
 *
 *  The FAULT pin is open-drain with an external pull-up resistor.
 *  Normal operation:  FAULT = HIGH  (pulled up, no fault)
 *  Fault condition:   FAULT = LOW   (driver pulls it down)
 *
 *  Possible faults (from TPS1H200A datasheet table 7-2):
 *    - Overload or short-to-GND  (current limit triggered)
 *    - Open load or short-to-battery  (output current too low)
 *    - Thermal shutdown  (chip too hot, output turned off)
 *    - Thermal swing  (rapid temperature change detected)
 *
 *  Since the FAULT pin is just one digital signal, we can't tell
 *  WHICH fault happened - only that SOMETHING is wrong.  The
 *  TPS1H200A's CL (current limit) pin analog voltage could be
 *  read via ADC to distinguish fault types, but we don't do that
 *  here.
 *
 *  Parameters:
 *    fault_pin  -  the dpin_t for the FAULT input (e.g. PD2)
 *    name       -  human-readable name for debug prints
 *
 *  Returns:
 *    true   -  no fault (FAULT pin is HIGH = normal)
 *    false  -  fault detected (FAULT pin is LOW)
 * --------------------------------------------------------------- */
static bool contactor_check_fault(dpin_t fault_pin, const char *name)
{
    /* Read the FAULT pin.  LOW = fault, HIGH = OK. */
    if (digital_read(fault_pin) == LOW)
    {
        /* Something is wrong with this driver.
         * Print which one so the user knows where to look. */
        char buf[80];

        snprintf(buf, sizeof(buf),
                 "  FAULT: %s driver reports fault (pin LOW)!\r\n",
                 name);
        board_dbg(buf);

        board_dbg("  Possible causes (TPS1H200A-Q1):\r\n");
        board_dbg("    - Overload or short-to-GND\r\n");
        board_dbg("    - Open load (contactor coil disconnected?)\r\n");
        board_dbg("    - Thermal shutdown or thermal swing\r\n");
        return false;   /* Fault detected */
    }

    return true;   /* No fault - all good */
}


/* ---------------------------------------------------------------
 *  contactor_all_off  -  Emergency: open every contactor
 *
 *  Called when something goes wrong during startup.  Opens all
 *  three contactors (precharge, positive, negative) and disables
 *  diagnostics.  This puts the system in a safe state.
 *
 *  We open in reverse order: precharge first (stop charging the
 *  bus), then positive (disconnect load side), then negative
 *  (disconnect battery side).
 * --------------------------------------------------------------- */
static void contactor_all_off(void)
{
    board_dbg("  -> Opening all contactors (safe state)\r\n");

    digital_write(PD3, LOW);    /* Open precharge  (MCU_PRECHARGE)  */
    digital_write(PD5, LOW);    /* Open positive   (MCU_CONTACTOR+) */
    digital_write(PC9, LOW);    /* Open negative   (MCU_CONTACTOR-) */

    /* Disable diagnostics to save power.
     * With DIAG_EN LOW and IN LOW, the TPS1H200A enters its
     * lowest power state (< 500 nA standby current). */
    digital_write(PA15, LOW);   /* DIAG_EN_CONTACTORS off */
}


/* ===============================================================
 *  board_contactor_startup
 *
 *  Closes the battery contactors in the correct order, checking
 *  for TPS1H200A driver faults at each step.
 *
 *  The sequence follows the Nissan Leaf charge turn-on timing:
 *
 *    Time (ms)   Action
 *    ---------   ----------------------------------
 *         0      Close negative contactor
 *       200      Close precharge contactor
 *    200-700     Wait for HV bus to charge (PB14 HIGH)
 *       ~700     Close positive contactor
 *       ~800     Open precharge contactor
 *
 *  If PB14 does not go HIGH within 500 ms of precharge closing,
 *  something is wrong (precharge resistor blown, contactor stuck
 *  open, etc.) so we abort and open everything.
 * =============================================================== */
bool board_contactor_startup(void)
{
    board_dbg("\r\n=== CONTACTOR STARTUP BEGIN ===\r\n");

    /* ------ Step 1: Enable diagnostics on all 3 drivers ------
     *
     * PA15 is wired to the DIAG_EN pin on all three TPS1H200A
     * drivers.  Setting it HIGH enables fault reporting on the
     * FAULT pins.  Without this, the FAULT pins don't indicate
     * problems (though the internal protections still work).
     */
    board_dbg("  Enabling driver diagnostics (PA15 HIGH)\r\n");
    digital_write(PA15, HIGH);

    /* Give the drivers a moment to wake up their diagnostic
     * circuitry.  The TPS1H200A needs very little time here
     * but 5 ms is safe. */
    HAL_Delay(5);

    /* ------ Step 2: Close negative contactor ------
     *
     * PC9 = MCU_CONTACTOR- = IN pin on the negative TPS1H200A.
     * Setting it HIGH turns on the MOSFET inside the driver,
     * which sends current through the contactor coil, pulling
     * the contacts closed.
     *
     * The negative contactor closes FIRST because it connects
     * the battery ground side.  No current flows yet because
     * the positive side is still open.
     */
    board_dbg("  Closing NEGATIVE contactor (PC9 HIGH)\r\n");
    digital_write(PC9, HIGH);

    /* Wait 10 ms for the driver to settle and the contactor
     * to physically close, then check for faults.
     * The TPS1H200A's open-load deglitch time is ~300 us,
     * so 10 ms is more than enough. */
    HAL_Delay(10);

    if (!contactor_check_fault(PD2, "CONTACTOR-"))
    {
        /* Negative driver faulted - abort everything */
        board_dbg("=== CONTACTOR STARTUP ABORTED (NEG FAULT) ===\r\n");
        contactor_all_off();
        return false;
    }

    /* ------ Step 3: Wait 200 ms ------
     *
     * This gap between closing the negative and starting
     * precharge matches the Nissan Leaf timing.  It ensures
     * the negative contactor is fully seated before we start
     * pushing current through the precharge path.
     * (We already waited 10 ms above, so 190 ms more.)
     */
    HAL_Delay(190);

    /* ------ Step 4: Close precharge contactor ------
     *
     * PD3 = MCU_PRECHARGE = IN pin on the precharge TPS1H200A.
     * The precharge contactor has a resistor in series that
     * limits inrush current while the DC bus capacitors charge
     * up.  Without precharge, slamming the positive contactor
     * closed would cause a huge current spike that could weld
     * the contactor contacts or blow fuses.
     */
    board_dbg("  Closing PRECHARGE contactor (PD3 HIGH)\r\n");
    digital_write(PD3, HIGH);

    /* Wait 10 ms for the driver to settle, then check fault */
    HAL_Delay(10);

    if (!contactor_check_fault(PD4, "PRECHARGE"))
    {
        /* Precharge driver faulted - abort */
        board_dbg("=== CONTACTOR STARTUP ABORTED (PCHG FAULT) ===\r\n");
        contactor_all_off();
        return false;
    }

    /* ------ Step 5: Wait for HV bus to charge (PB14 HIGH) ------
     *
     * PB14 = MCU_HV_PRESENT.  This pin is connected to a voltage
     * divider on the DC bus.  When the bus capacitors charge up
     * through the precharge resistor, PB14 goes HIGH.
     *
     * We poll every 10 ms and give it a maximum of 500 ms.
     * If PB14 doesn't go HIGH in time, something is wrong:
     *   - Precharge resistor is blown / open
     *   - Contactor didn't actually close
     *   - DC bus has a short circuit
     *   - Voltage divider circuit fault
     */
    board_dbg("  Waiting for HV bus to charge (PB14 HIGH)...\r\n");

    {
        /* 500 ms timeout, polling every 10 ms = 50 iterations max */
        uint16_t polls = 0;
        const uint16_t max_polls = 50;   /* 50 x 10 ms = 500 ms */
        bool hv_ok = false;

        while (polls < max_polls)
        {
            /* Check if the bus voltage has reached the threshold */
            if (digital_read(PB14) == HIGH)
            {
                hv_ok = true;
                break;
            }

            /* Also check precharge fault each iteration -
             * if the precharge driver faults mid-charge we
             * want to know immediately, not wait 500 ms. */
            if (!contactor_check_fault(PD4, "PRECHARGE"))
            {
                board_dbg("=== CONTACTOR STARTUP ABORTED "
                          "(PCHG FAULT DURING CHARGE) ===\r\n");
                contactor_all_off();
                return false;
            }

            HAL_Delay(10);
            polls++;
        }

        if (!hv_ok)
        {
            /* Timed out - HV bus never charged up */
            char buf[64];

            snprintf(buf, sizeof(buf),
                     "  TIMEOUT: PB14 not HIGH after %u ms!\r\n",
                     (unsigned)(polls * 10));
            board_dbg(buf);
            board_dbg("  Check: precharge resistor, contactor, bus\r\n");
            board_dbg("=== CONTACTOR STARTUP ABORTED (TIMEOUT) ===\r\n");
            contactor_all_off();
            return false;
        }

        /* Print how long it took - useful for diagnostics */
        {
            char buf[64];

            snprintf(buf, sizeof(buf),
                     "  HV bus charged OK after ~%u ms\r\n",
                     (unsigned)(polls * 10));
            board_dbg(buf);
        }
    }

    /* ------ Step 6: Close positive contactor ------
     *
     * PD5 = MCU_CONTACTOR+ = IN pin on the positive TPS1H200A.
     * Now that the bus is pre-charged, it's safe to close the
     * main positive contactor.  The voltage across the contactor
     * contacts is nearly zero (bus is already at battery voltage)
     * so there's no inrush current spike.
     */
    board_dbg("  Closing POSITIVE contactor (PD5 HIGH)\r\n");
    digital_write(PD5, HIGH);

    /* Wait 10 ms then check for faults */
    HAL_Delay(10);

    if (!contactor_check_fault(PC8, "CONTACTOR+"))
    {
        /* Positive driver faulted - abort */
        board_dbg("=== CONTACTOR STARTUP ABORTED (POS FAULT) ===\r\n");
        contactor_all_off();
        return false;
    }

    /* ------ Step 7: Open precharge contactor ------
     *
     * The precharge path is no longer needed because the main
     * positive contactor is now carrying the current.  Leaving
     * precharge closed wastes energy through the resistor and
     * could overheat it.
     *
     * Wait 100 ms after positive closes to ensure the main
     * contactor is fully seated before removing the parallel
     * precharge path.
     */
    HAL_Delay(100);

    board_dbg("  Opening PRECHARGE contactor (PD3 LOW)\r\n");
    digital_write(PD3, LOW);

    /* ------ Final fault check ------
     *
     * Do one last check on both main contactors now that
     * the full load current is flowing through them.
     */
    HAL_Delay(10);

    if (!contactor_check_fault(PD2, "CONTACTOR-"))
    {
        board_dbg("=== CONTACTOR STARTUP ABORTED "
                  "(NEG FAULT UNDER LOAD) ===\r\n");
        contactor_all_off();
        return false;
    }

    if (!contactor_check_fault(PC8, "CONTACTOR+"))
    {
        board_dbg("=== CONTACTOR STARTUP ABORTED "
                  "(POS FAULT UNDER LOAD) ===\r\n");
        contactor_all_off();
        return false;
    }

    board_dbg("=== CONTACTOR STARTUP OK - HV BUS LIVE ===\r\n");
    return true;
}


/* ===============================================================
 *  board_contactor_shutdown
 *
 *  Opens the battery contactors in the safe reverse order:
 *    1. Positive first  (disconnect load from battery)
 *    2. Precharge       (in case it's still on for some reason)
 *    3. Negative last   (disconnect battery ground)
 *
 *  The gaps between steps give each contactor time to physically
 *  open and extinguish any arc across the contacts.  The positive
 *  opens first because it's carrying the main current - once it's
 *  open, the negative has no current to interrupt.
 *
 *  We also disable driver diagnostics afterwards to save power.
 *  With DIAG_EN and IN both LOW, each TPS1H200A enters standby
 *  at < 500 nA.
 * =============================================================== */
void board_contactor_shutdown(void)
{
    board_dbg("\r\n=== CONTACTOR SHUTDOWN BEGIN ===\r\n");

    /* ------ Step 1: Open positive contactor ------
     *
     * PD5 LOW = turn off the positive TPS1H200A MOSFET.
     * The contactor coil de-energises and the spring opens
     * the contacts.  The TPS1H200A has an internal clamp
     * diode that handles the inductive kick from the coil.
     */
    board_dbg("  Opening POSITIVE contactor (PD5 LOW)\r\n");
    digital_write(PD5, LOW);

    /* Wait 50 ms for the contactor to physically open */
    HAL_Delay(50);

    /* ------ Step 2: Open precharge contactor ------
     *
     * PD3 LOW.  This should already be open from the startup
     * sequence step 7, but we do it here as a safety measure.
     * Belt and braces!
     */
    board_dbg("  Opening PRECHARGE contactor (PD3 LOW)\r\n");
    digital_write(PD3, LOW);

    /* Wait 50 ms */
    HAL_Delay(50);

    /* ------ Step 3: Open negative contactor ------
     *
     * PC9 LOW.  No current flowing through it at this point
     * because the positive is already open.  This is the safest
     * order - opening the negative under load could cause arcing.
     */
    board_dbg("  Opening NEGATIVE contactor (PC9 LOW)\r\n");
    digital_write(PC9, LOW);

    /* ------ Step 4: Disable diagnostics ------
     *
     * PA15 LOW.  Puts all three TPS1H200A drivers into their
     * lowest power state.  The FAULT pins become inactive but
     * that doesn't matter because everything is off now.
     */
    HAL_Delay(10);
    board_dbg("  Disabling driver diagnostics (PA15 LOW)\r\n");
    digital_write(PA15, LOW);

    board_dbg("=== CONTACTOR SHUTDOWN COMPLETE ===\r\n");
}


/* ===============================================================
 *  MCU-level voltage warning outputs
 *
 *  Three GPIOs act as live status indicators:
 *    PA5 = MCU_OVER_VOLTAGE   (HIGH when any cell is too high)
 *    PA4 = MCU_BALANCING      (HIGH when any cell needs balancing)
 *    PA6 = MCU_UNDER_VOLTAGE  (HIGH when any cell is too low)
 *
 *  Thresholds stored in static variables, set once at startup.
 *  board_check_voltage_warnings() compares every cell against
 *  these thresholds each loop pass.
 *
 *  Non-latching: pin goes LOW the instant no cell meets the
 *  condition.  No hysteresis by design — these are informational
 *  warnings, not fault latches.
 * =============================================================== */

/* ---- Static storage for the three thresholds ----
 *
 * Initialised to 0 which means "not configured".
 * board_check_voltage_warnings() skips any threshold that
 * is 0, so warnings are inactive until setters are called.
 */
static uint16_t warn_ov_mv  = 0;   /* OV:  trigger when cell >= this */
static uint16_t warn_bal_mv = 0;   /* BAL: trigger when cell >= this */
static uint16_t warn_uv_mv  = 0;   /* UV:  trigger when cell <= this */


/* ---------------------------------------------------------------
 *  board_set_ov_warn_thresh  –  Set overvoltage warning level
 *
 *  When any cell voltage >= this value, PA5 goes HIGH.
 *  Typical: 4150 mV (25 mV below BQ79616 OV fault at 4175).
 * --------------------------------------------------------------- */
void board_set_ov_warn_thresh(uint16_t mv)
{
    warn_ov_mv = mv;

    char buf[64];

    snprintf(buf, sizeof(buf),
             "  OV  warn thresh = %u mV (PA5)\r\n",
             (unsigned)mv);
    board_dbg(buf);
}


/* ---------------------------------------------------------------
 *  board_set_bal_warn_thresh  –  Set balance warning level
 *
 *  When any cell voltage >= this value, PA4 goes HIGH.
 *  Typical: 4085 mV (signals cells are nearing full charge
 *  and balancing should be active).
 * --------------------------------------------------------------- */
void board_set_bal_warn_thresh(uint16_t mv)
{
    warn_bal_mv = mv;

    char buf[64];

    snprintf(buf, sizeof(buf),
             "  BAL warn thresh = %u mV (PA4)\r\n",
             (unsigned)mv);
    board_dbg(buf);
}


/* ---------------------------------------------------------------
 *  board_set_uv_warn_thresh  –  Set undervoltage warning level
 *
 *  When any cell voltage <= this value, PA6 goes HIGH.
 *  Typical: 3150 mV (50 mV above BQ79616 UV fault at 3100).
 * --------------------------------------------------------------- */
void board_set_uv_warn_thresh(uint16_t mv)
{
    warn_uv_mv = mv;

    char buf[64];

    snprintf(buf, sizeof(buf),
             "  UV  warn thresh = %u mV (PA6)\r\n",
             (unsigned)mv);
    board_dbg(buf);
}


/* ---------------------------------------------------------------
 *  board_check_voltage_warnings  –  Scan cells, drive GPIOs
 *
 *  Walks through the cell voltage array and checks each cell
 *  against the three thresholds.  If ANY cell triggers a
 *  condition, the GPIO goes HIGH.  If NO cell triggers, LOW.
 *
 *  Cost: ~16 comparisons + 3 GPIO writes.  No UART, no BQ79616
 *  register access — just reading numbers already in RAM.
 *
 *  Parameters:
 *    cell_mv   - array of cell voltages in millivolts
 *    num_cells - how many valid entries (1..16)
 * --------------------------------------------------------------- */
void board_check_voltage_warnings(const int32_t cell_mv[],
                                  uint8_t       num_cells)
{
    uint8_t ov_triggered  = 0;   /* 1 if any cell >= OV threshold  */
    uint8_t bal_triggered = 0;   /* 1 if any cell >= BAL threshold */
    uint8_t uv_triggered  = 0;   /* 1 if any cell <= UV threshold  */
    uint8_t i;

    /* Single pass through all cells, checking all three
     * conditions at once for efficiency. */
    for (i = 0; i < num_cells; i++)
    {
        int32_t v = cell_mv[i];

        /* Skip invalid readings (BQ reset value = 0 mV,
         * or negative from conversion errors).
         * A valid lithium cell is always above 1000 mV. */
        if (v < 1000)
        {
            continue;
        }

        /* Overvoltage: cell >= threshold */
        if ((warn_ov_mv > 0) && (v >= (int32_t)warn_ov_mv))
        {
            ov_triggered = 1;
        }

        /* Balance: cell >= threshold */
        if ((warn_bal_mv > 0) && (v >= (int32_t)warn_bal_mv))
        {
            bal_triggered = 1;
        }

        /* Undervoltage: cell <= threshold (note <= direction) */
        if ((warn_uv_mv > 0) && (v <= (int32_t)warn_uv_mv))
        {
            uv_triggered = 1;
        }
    }

    /* Drive the three GPIO outputs.
     * Non-latching: pin goes LOW immediately when
     * the condition clears. */
    digital_write(PA5, ov_triggered  ? HIGH : LOW);  /* MCU_OVER_VOLTAGE  */
    digital_write(PA4, bal_triggered ? HIGH : LOW);   /* MCU_BALANCING     */
    digital_write(PA6, uv_triggered  ? HIGH : LOW);   /* MCU_UNDER_VOLTAGE */
}


